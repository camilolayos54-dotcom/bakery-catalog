// Builds src/db/initialData.ts and src/db/seedImages.data.ts from an organized backup + photo thumbnails.
// Usage: tsx scripts/build_seed.ts <backup.json> <thumbs-dir>   (thumbs-dir holds <productId>.txt with base64 JPEG)
import * as fs from 'fs';
import * as path from 'path';

const [backupPath, thumbsDir] = process.argv.slice(2);
if (!backupPath || !thumbsDir) throw new Error('usage: build_seed.ts <backup.json> <thumbs-dir>');

type B = {
  groups: { id: number; name: string; sort_order: number }[];
  subcategories: { id: number; group_id: number; name: string; sort_order: number }[];
  products: {
    id: number;
    name: string;
    price_cents: number;
    group_id: number;
    subcategory_id: number | null;
    created_at: number;
    promo_qty: number | null;
    promo_price_cents: number | null;
    sort_order: number;
  }[];
};
const b = JSON.parse(fs.readFileSync(backupPath, 'utf8')) as B;

const images: Record<string, string> = {};
const q = (s: string) => JSON.stringify(s);

let ts = `// Generated by scripts/build_seed.ts from the organized phone backup. Do not edit by hand.
// A fresh install starts with this catalog (and its photos, see seedImages.data.ts).

export type SeedProduct = {
  name: string;
  price_cents: number;
  subcategory?: string | null;
  promo_qty?: number | null;
  promo_price_cents?: number | null;
  /** Key into SEED_IMAGES (seedImages.data.ts). */
  image?: string;
  created_at?: number;
  sort_order?: number;
};

export type SeedCategory = {
  name: string;
  sort_order: number;
  subcategories: string[];
  products: SeedProduct[];
};

export const INITIAL_CATALOG: SeedCategory[] = [
`;

for (const g of b.groups.slice().sort((x, y) => x.sort_order - y.sort_order)) {
  const subs = b.subcategories.filter((s) => s.group_id === g.id).sort((x, y) => x.sort_order - y.sort_order);
  const subName = new Map(subs.map((s) => [s.id, s.name]));
  ts += `  {\n    name: ${q(g.name)},\n    sort_order: ${g.sort_order},\n    subcategories: [${subs.map((s) => q(s.name)).join(', ')}],\n    products: [\n`;
  const prods = b.products.filter((p) => p.group_id === g.id).sort((x, y) => x.created_at - y.created_at || x.id - y.id);
  for (const p of prods) {
    const parts = [`name: ${q(p.name)}`, `price_cents: ${p.price_cents}`];
    if (p.subcategory_id != null) parts.push(`subcategory: ${q(subName.get(p.subcategory_id)!)}`);
    if (p.promo_qty && p.promo_price_cents) parts.push(`promo_qty: ${p.promo_qty}`, `promo_price_cents: ${p.promo_price_cents}`);
    const thumb = path.join(thumbsDir, `${p.id}.txt`);
    if (fs.existsSync(thumb)) {
      const key = `seed_${p.id}`;
      images[key] = fs.readFileSync(thumb, 'utf8').trim();
      parts.push(`image: ${q(key)}`);
    }
    parts.push(`created_at: ${p.created_at}`, `sort_order: ${p.sort_order}`);
    ts += `      { ${parts.join(', ')} },\n`;
  }
  ts += `    ],\n  },\n`;
}
ts += `];\n`;

const root = path.resolve(__dirname, '..');
fs.writeFileSync(path.join(root, 'src/db/initialData.ts'), ts);

let img = `// Generated by scripts/build_seed.ts. Product photos (480 px JPEG, base64) bundled with the app.\n\nexport const SEED_IMAGES: Record<string, string> = {\n`;
for (const [k, v] of Object.entries(images)) img += `  ${k}: ${q(v)},\n`;
img += `};\n`;
fs.writeFileSync(path.join(root, 'src/db/seedImages.data.ts'), img);

console.log('products', b.products.length, 'images', Object.keys(images).length);
